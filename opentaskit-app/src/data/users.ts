export function userById(id: string): User {
  return users.find((u) => u.id === id) ?? users[0];
}

/** Everyone offering work in a category, available members first then nearest. */
export function providersForCategory(categoryId: string): User[] {
  return users.
  filter((u) => u.categoryIds.includes(categoryId)).
  sort((a, b) => Number(b.available) - Number(a.available) || a.distanceKm - b.distanceKm);
}